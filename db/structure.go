package db

import (
	"context"
	"fmt"
	"strings"

	"github.com/crgimenes/dbv/sqlcomplete"
)

type Column struct {
	Name      string
	Type      string // format_type with its modifier: varchar(80), numeric(10,2)
	NotNull   bool
	Default   string // the expression; "" none
	Identity  string // "a" always, "d" by default, "" not one
	Generated string // "s" stored, "" not one
	Key       bool   // in the primary key
	Comment   string
}

func (pg *Postgres) Structure(ctx context.Context, rel Rel) ([]Column, error) {
	const q = `SELECT
	a.attname,                                            -- 1
	format_type(a.atttypid, a.atttypmod),                 -- 2
	a.attnotnull,                                         -- 3
	COALESCE(pg_get_expr(d.adbin, d.adrelid), ''),        -- 4
	a.attidentity::text,                                  -- 5
	a.attgenerated::text,                                 -- 6
	EXISTS (SELECT 1 FROM pg_index i
	        WHERE i.indrelid = a.attrelid AND i.indisprimary
	          AND a.attnum = ANY(i.indkey[0:i.indnkeyatts - 1])), -- 7
	COALESCE(col_description(a.attrelid, a.attnum), '')   -- 8
FROM pg_attribute a
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = $1 AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum`
	rows, err := pg.DB.QueryContext(ctx, q, rel.OID)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	var out []Column
	for rows.Next() {
		var c Column
		err = rows.Scan(
			&c.Name,      // 1
			&c.Type,      // 2
			&c.NotNull,   // 3
			&c.Default,   // 4
			&c.Identity,  // 5
			&c.Generated, // 6
			&c.Key,       // 7
			&c.Comment,   // 8
		)
		if err != nil {
			return nil, err
		}
		out = append(out, c)
	}
	return out, rows.Err()
}

// Constraint is a constraint of a table, or an index no constraint owns.
type Constraint struct {
	Name string
	Kind string // p primary key, u unique, f foreign key, c check, x exclusion, i index
	Def  string // what follows ADD CONSTRAINT name; an index's CREATE INDEX
	SQL  string // an index's name as DROP INDEX takes it: schema and quotes
}

// Constraints reads rel's constraints, then the indexes that back none,
// key first. Not-null constraints are left out: the columns show them.
func (pg *Postgres) Constraints(ctx context.Context, rel Rel) ([]Constraint, error) {
	const q = `SELECT name, kind, def, sqlname FROM (
	SELECT c.conname AS name, c.contype::text AS kind,
	       pg_get_constraintdef(c.oid, true) AS def, '' AS sqlname,
	       array_position(ARRAY['p', 'u', 'f', 'c', 'x'], c.contype::text) AS rank
	FROM pg_constraint c
	WHERE c.conrelid = $1 AND c.contype IN ('p', 'u', 'f', 'c', 'x')
	UNION ALL
	SELECT ic.relname, 'i', pg_get_indexdef(i.indexrelid), i.indexrelid::regclass::text, 6
	FROM pg_index i
	JOIN pg_class ic ON ic.oid = i.indexrelid
	WHERE i.indrelid = $1
	  AND NOT EXISTS (SELECT 1 FROM pg_constraint c
	                  WHERE c.conrelid = i.indrelid AND c.conindid = i.indexrelid
	                    AND c.contype IN ('p', 'u', 'x'))
) s
ORDER BY rank, name`
	rows, err := pg.DB.QueryContext(ctx, q, rel.OID)
	if err != nil {
		return nil, err
	}
	defer func() { _ = rows.Close() }()
	var out []Constraint
	for rows.Next() {
		var c Constraint
		err = rows.Scan(&c.Name, &c.Kind, &c.Def, &c.SQL)
		if err != nil {
			return nil, err
		}
		out = append(out, c)
	}
	return out, rows.Err()
}

// DDL is rel as the statements that make it, laid out to read: a table's
// CREATE TABLE a column a line, its constraints, indexes and comments; a
// view's or a materialized view's definition.
func (pg *Postgres) DDL(ctx context.Context, rel Rel) (string, error) {
	switch rel.Kind {
	case "v":
		def, _, err := pg.ViewDef(ctx, rel)
		return strings.Replace(def, "CREATE OR REPLACE VIEW", "CREATE VIEW", 1), err
	case "m":
		script, _, err := pg.MatViewDef(ctx, rel)
		_, script, _ = strings.Cut(script, "\n") // its DROP
		return script, err
	}
	cols, err := pg.Structure(ctx, rel)
	if err != nil {
		return "", err
	}
	cons, err := pg.Constraints(ctx, rel)
	if err != nil {
		return "", err
	}
	width := 0
	for _, c := range cols {
		width = max(width, len(sqlcomplete.Name(c.Name)))
	}
	var lines, after []string
	for _, c := range cols {
		line := fmt.Sprintf("%-*s %s", width, sqlcomplete.Name(c.Name), c.Type)
		switch {
		case c.Identity == "a":
			line += " GENERATED ALWAYS AS IDENTITY"
		case c.Identity == "d":
			line += " GENERATED BY DEFAULT AS IDENTITY"
		case c.Generated == "s":
			line += " GENERATED ALWAYS AS (" + c.Default + ") STORED"
		case c.Default != "":
			line += " DEFAULT " + c.Default
		}
		if c.NotNull {
			line += " NOT NULL"
		}
		lines = append(lines, line)
		if c.Comment != "" {
			after = append(after, "COMMENT ON COLUMN "+rel.SQL+"."+sqlcomplete.Name(c.Name)+" IS "+QuoteLiteral(c.Comment)+";")
		}
	}
	var indexes []string
	for _, k := range cons {
		if k.Kind == "i" {
			indexes = append(indexes, k.Def+";")
			continue
		}
		lines = append(lines, "CONSTRAINT "+sqlcomplete.Name(k.Name)+" "+k.Def)
	}
	const q = `SELECT COALESCE(obj_description(c.oid, 'pg_class'), ''),
	COALESCE(' PARTITION BY ' || pg_get_partkeydef(c.oid), ''),
	COALESCE((SELECT ' INHERITS (' || string_agg(i.inhparent::regclass::text, ', ' ORDER BY i.inhseqno) || ')'
	          FROM pg_inherits i WHERE i.inhrelid = c.oid AND NOT c.relispartition), ''),
	COALESCE((SELECT 'ALTER TABLE ' || i.inhparent::regclass::text || ' ATTACH PARTITION ' || c.oid::regclass::text
	                 || ' ' || pg_get_expr(c.relpartbound, c.oid) || ';'
	          FROM pg_inherits i WHERE i.inhrelid = c.oid AND c.relispartition), '')
FROM pg_class c WHERE c.oid = $1`
	var comment, partBy, inherits, attach string
	err = pg.DB.QueryRowContext(ctx, q, rel.OID).Scan(&comment, &partBy, &inherits, &attach)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("CREATE TABLE " + rel.SQL + " (\n    " + strings.Join(lines, ",\n    ") + "\n)" + inherits + partBy + ";\n")
	if attach != "" {
		b.WriteString("\n" + attach + "\n")
	}
	if len(indexes) > 0 {
		b.WriteString("\n" + strings.Join(indexes, "\n") + "\n")
	}
	if comment != "" {
		after = append([]string{"COMMENT ON TABLE " + rel.SQL + " IS " + QuoteLiteral(comment) + ";"}, after...)
	}
	if len(after) > 0 {
		b.WriteString("\n" + strings.Join(after, "\n") + "\n")
	}
	return b.String(), nil
}
